import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const window={};vm.runInNewContext(fs.readFileSync('dist/learning.js','utf8'),{window});
const {expected,explain}=window.wordylandLearning;
assert.equal(expected({kind:'missing',word:'head',mask:'h_ad'}),'e');
assert.equal(expected({kind:'gap',word:'the cat is under the box',mask:'the cat is _____ the box'}),'under');
assert.match(explain({expected:'under',answer:'on',word:'the cat is under the box',kind:'choice'}),/sopra.*sotto.*under/);
assert.match(explain({expected:'next to',answer:'behind',kind:'choice'}),/dietro.*accanto/);
assert.match(explain({expected:'e',answer:'a',word:'head',kind:'missing'}),/lettera «e».*«head»/);
assert.match(explain({expected:'head',answer:'hed',kind:'write'}),/Dopo «he» serve «a»/);
assert.match(explain({expected:'head',answer:'hea',kind:'write'}),/Manca ancora «d»/);
assert.match(explain({expected:'head',answer:'heads',kind:'write'}),/«s» in più/);
assert.match(explain({expected:'under',answer:'the cat is under the box',word:'the cat is under the box',kind:'gap'}),/solo la parte mancante/);
assert.match(explain({expected:'three pencils',answer:'two pencils',kind:'count'}),/scelto 2.*sono 3/);
assert.match(explain({expected:'three',answer:'3',kind:'count'}),/scrivilo in inglese/);
assert.match(explain({expected:'one pencil',answer:'one pencils',kind:'count'}),/non vuole la s/);
for(const [prompt,rule] of [['What is your name?','il nome'],['How old are you?','quanti anni'],['How are you?','come stai']])assert(explain({expected:'sample',answer:'other',kind:'dialogue',prompt}).includes(rule));
assert.match(explain({expected:'head',answer:'hand',translation:'testa',chosenTranslation:'mano',kind:'choice'}),/«mano».*«testa».*«head»/);
console.log('Learning feedback: position meanings, letters, missing/extra spelling, gaps, quantity and dialogue explanations passed.');
